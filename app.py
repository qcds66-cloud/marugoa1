# --- 漢字假名解析演算法 ---
def is_kanji(ch):
    return "\u4e00" <= ch <= "\u9faf" or "\u3400" <= ch <= "\u4dbf"


def parse_kanji_sentence(kanji_text):
    tokens = []
    if not kanji_text:
        return tokens
    curr_is_kanji = is_kanji(kanji_text[0])
    curr_str = ""
    for ch in kanji_text:
        k = is_kanji(ch)
        if k == curr_is_kanji:
            curr_str += ch
        else:
            tokens.append((curr_is_kanji, curr_str))
            curr_is_kanji = k
            curr_str = ch
    if curr_str:
        tokens.append((curr_is_kanji, curr_str))
    return tokens


def find_kana_tok(kana_text, tok, pos):
    idx = kana_text.find(tok, pos)
    if idx != -1:
        return idx, len(tok)
    clean_tok = "".join([c for c in tok if not is_kanji(c) and c.isalnum()])
    if clean_tok:
        idx = kana_text.find(clean_tok, pos)
        if idx != -1:
            return idx, len(clean_tok)
        for length in range(min(4, len(clean_tok)), 0, -1):
            sub = clean_tok[:length]
            idx = kana_text.find(sub, pos)
            if idx != -1:
                return idx, len(sub)
    return -1, 0


def render_matched_html(kanji_text, kana_text):
    """將假名中與漢字對應的字段標示為莫蘭迪藍色 CSS"""
    tokens = parse_kanji_sentence(kanji_text)
    html_out = ""
    pos = 0

    for i, (is_k, tok) in enumerate(tokens):
        if not is_k:
            idx, match_len = find_kana_tok(kana_text, tok, pos)
            if idx != -1:
                if idx > pos:
                    html_out += kana_text[pos:idx]
                html_out += kana_text[idx : idx + match_len]
                pos = idx + match_len
            else:
                html_out += tok
        else:
            if i + 1 < len(tokens):
                next_is_k, next_tok = tokens[i + 1]
                idx, _ = find_kana_tok(kana_text, next_tok, pos)
                if idx != -1:
                    kana_segment = kana_text[pos:idx]
                    pos = idx
                else:
                    kana_segment = kana_text[pos:]
                    pos = len(kana_text)
            else:
                kana_segment = kana_text[pos:]
                pos = len(kana_text)

            m = re.match(r"^(\s*)(.*?)(\s*)$", kana_segment, re.DOTALL)
            if m:
                lead, core, trail = m.group(1), m.group(2), m.group(3)
                if lead:
                    html_out += lead
                if core:
                    html_out += f'<span style="color: #3B6982; font-weight: bold;">{core}</span>'
                if trail:
                    html_out += trail
            else:
                html_out += f'<span style="color: #3B6982; font-weight: bold;">{kana_segment}</span>'

    if pos < len(kana_text):
        html_out += kana_text[pos:]

    return html_out


# --- HTML5 Web Speech API 播報元件 ---
def generate_speech_js(text_to_speak):
    """利用 HTML5 的 SpeechSynthesis 產生本機端發音，完全不需要依賴第三方伺服器"""
    if not text_to_speak:
        return ""
    # 處理跳脫字元
    safe_text = (
        text_to_speak.replace("\\", "\\\\")
        .replace("'", "\\'")
        .replace("\n", " ")
    )
    js_code = f"""
    <script>
    (function() {{
        if ('speechSynthesis' in window) {{
            window.speechSynthesis.cancel(); // 停止先前的語音
            var msg = new SpeechSynthesisUtterance('{safe_text}');
            msg.lang = 'ja-JP';
            msg.rate = 0.9;
            window.speechSynthesis.speak(msg);
        }}
    }})();
    </script>
    """
    return js_code


