def start_study(lesson):
    if lesson == "ALL":
        st.session_state.active_list = list(word_db)
    else:
        st.session_state.active_list = [w for w in word_db if w[0] == lesson]

    random.shuffle(st.session_state.active_list)
    st.session_state.current_idx = 0
    st.session_state.page = "study"
    st.rerun()


# --- 頁面 2：單字卡學習頁面 ---
def show_study():
    total_count = len(st.session_state.active_list)
    curr_idx = st.session_state.current_idx

    if curr_idx >= total_count:
        st.balloons()
        st.success("🎉 本單元學習完成！")
        if st.button("返回主選單", use_container_width=True):
            st.session_state.page = "menu"
            st.rerun()
        return

    data = st.session_state.active_list[curr_idx]

    # 上方頂部導覽列
    col_back, col_info = st.columns([1, 2])
    with col_back:
        if st.button("⬅️ 選單"):
            st.session_state.is_auto = False
            st.session_state.page = "menu"
            st.rerun()
    with col_info:
        st.markdown(
            f"**第 {data[0]} 課**（{curr_idx + 1} / {total_count}）"
        )

    # 頂部可隨時切換單字進度的下拉選單
    new_idx = st.selectbox(
        "快速跳轉單字",
        options=list(range(total_count)),
        format_func=lambda x: f"{x+1}. {st.session_state.active_list[x][1]} ({st.session_state.active_list[x][2]})",
        index=curr_idx,
        key="selector",
    )
    if new_idx != curr_idx:
        st.session_state.current_idx = new_idx
        st.rerun()

    st.markdown("---")

    # 單字卡片主體
    st.markdown(
        f"""
    <div style="background-color: #FFFFFF; padding: 20px; border-radius: 12px; border: 1px solid #E0E0E0; text-align: center; margin-bottom: 15px;">
        <h1 style="margin: 0; font-size: 2.8rem; color: #111;">{data[1]}</h1>
        <h3 style="margin: 5px 0; color: #3F51B5; font-size: 1.5rem;">{data[2]}</h3>
        <p style="margin: 0; color: #555; font-size: 1.2rem;">{data[3]}</p>
    </div>
    """,
        unsafe_allow_html=True,
    )

    # 例句卡片區
    matched_html = render_matched_html(data[4], data[5])
    st.markdown(
        f"""
    <div style="background-color: #FFFFFF; padding: 18px; border-radius: 12px; border: 1px solid #E0E0E0; margin-bottom: 20px;">
        <div style="font-size: 1.25rem; font-weight: bold; margin-bottom: 8px;">{data[4]}</div>
        <hr style="margin: 8px 0;">
        <div style="font-size: 1.15rem; font-family: monospace; margin-bottom: 8px;">{matched_html}</div>
        <div style="font-size: 1.1rem; color: #444;">{data[6]}</div>
    </div>
    """,
        unsafe_allow_html=True,
    )

    # 手動發音控制按鈕
    col_sound1, col_sound2 = st.columns(2)
    with col_sound1:
        if st.button("🔊 讀單字", use_container_width=True):
            st.components.v1.html(generate_speech_js(data[2]), height=0)
    with col_sound2:
        if st.button("🔊 讀例句", use_container_width=True):
            st.components.v1.html(generate_speech_js(data[4]), height=0)

    st.markdown("---")

    # 底部卡片導覽與自動播報控制
    col_p, col_auto, col_n = st.columns([1, 1.2, 1])

    with col_p:
        if st.button("◀ 上一個", use_container_width=True):
            if st.session_state.current_idx > 0:
                st.session_state.current_idx -= 1
                st.rerun()

    with col_n:
        if st.button("下一個 ▶", use_container_width=True):
            if st.session_state.current_idx < total_count - 1:
                st.session_state.current_idx += 1
                st.rerun()

    with col_auto:
        auto_label = (
            "⏸️ 暫停" if st.session_state.is_auto else "▶️ 自動朗讀"
        )
        if st.button(auto_label, use_container_width=True, type="primary"):
            st.session_state.is_auto = not st.session_state.is_auto
            st.rerun()

    # 自動朗讀模式處理邏輯
    if st.session_state.is_auto:
        # 自動執行發音
        st.components.v1.html(generate_speech_js(data[2]), height=0)
        if st.session_state.read_example:
            time.sleep(1.2)
            st.components.v1.html(generate_speech_js(data[4]), height=0)

        # 依照設定秒數等待後進入下一個單字
        time.sleep(st.session_state.pause_sec)
        if st.session_state.current_idx < total_count - 1:
            st.session_state.current_idx += 1
            st.rerun()
        else:
            st.session_state.is_auto = False
            st.rerun()


